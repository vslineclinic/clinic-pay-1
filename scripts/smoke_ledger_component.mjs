import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { EditorState } = require('../assets/ledger_editor/state.js');
let sequence = 0;
const state = new EditorState('scope', () => `req-${++sequence}`);
const base = {id:'a', receipt_revision:1, draft_revision:0, raw:{chart_no:'123', patient_name:'원본', payments:{카드:'100'}}};
state.sync([base]);
state.edit('a', 'patient_name', '내 입력');
state.sync([{...base, receipt_revision:2, raw:{...base.raw, patient_name:'다른 창'}}], new Set(['a']));
assert.equal(state.rows.get('a').raw.patient_name, '내 입력', 'poll must retain dirty focused value');
assert.equal(state.rows.get('a').receipt_revision, 1, 'dirty edits must retain old CAS revision');
state.composing.add('a');
assert.equal(state.next(), null, 'IME composition must not submit partial text');
state.composing.clear();
const first = state.next();
assert.equal(first.receipt_revision, 1);
assert.equal(state.next().request_id, first.request_id, 'lost response retry must reuse request id');
state.edit('a', 'patient_name', '입력 계속');
assert.equal(state.next().raw.patient_name, '내 입력', 'inflight payload cannot mutate');
state.ack({id:'a',request_id:first.request_id,status:'saved',receipt_revision:2,draft_revision:0});
const second = state.next();
assert.equal(second.raw.patient_name, '입력 계속');
assert.equal(second.receipt_revision,2, 'ordered changes must use ACK revision');
state.ack({id:'a',request_id:second.request_id,status:'conflict',current:{...base,revision:3,patient_name:'다른 창'},message:'충돌'});
assert.equal(state.rows.get('a').raw.patient_name,'입력 계속');
assert.equal(state.next(),null, 'conflict must pause until explicit resolution');
state.resolve('a','mine');
const resolution = state.next();
assert.equal(resolution.receipt_revision,3);
assert.equal(resolution.raw.patient_name,'입력 계속');
assert.notEqual(resolution.request_id,second.request_id);
state.ack({id:'a',request_id:resolution.request_id,status:'draft',draft_revision:1,receipt_revision:3});
assert.equal(state.rows.get('a').status,'draft');
state.sync([{...base,receipt_revision:3,draft_revision:1,raw:{...base.raw,patient_name:'입력 계속'}}]);
state.edit('a','카드','not money',true);
const invalid = state.next();
assert.equal(invalid.raw.payments.카드,'not money');
state.ack({id:'a',request_id:invalid.request_id,status:'error',message:'다시 시도'});
assert.equal(state.next(),null,'error must retain raw and stop automatic loop');
state.retry('a');
assert.equal(state.next().request_id,invalid.request_id,'unknown error retry keeps same request');
const other = new EditorState('other', () => 'other');
other.sync([{...base,raw:{...base.raw,patient_name:'다른 일자'}}]);
assert.equal(other.rows.get('a').raw.patient_name,'다른 일자','day scope cannot share mutable rows');
console.log('Ledger component state: 19 assertions passed');
const queue = new EditorState('queue', () => `queue-${++sequence}`);
queue.sync([base,{...base,id:'b'}]);
queue.edit('a','patient_name','A');const qa=queue.next();
queue.ack({id:'a',request_id:qa.request_id,status:'error',message:'connection'});
queue.edit('b','patient_name','B');const qb=queue.next();
queue.edit('a','patient_name','A continued');
assert.equal(queue.next().request_id,qb.request_id,'editing a failed row must not cancel another inflight row');
queue.retry('a');
assert.equal(queue.next().request_id,qb.request_id,'retry must wait for another inflight request');
queue.ack({id:'b',request_id:qb.request_id,status:'saved',receipt_revision:2,draft_revision:0});
const retried=queue.next();assert.equal(retried.request_id,qa.request_id);
assert.equal(retried.raw.patient_name,'A','retry must retain original immutable command');
assert.equal(retried.attempt,1);
queue.ack({id:'a',request_id:qa.request_id,status:'error',message:'old ACK'});
assert.equal(queue.next().request_id,qa.request_id,'old attempt ACK must not terminate a new retry');
queue.ack({id:'a',request_id:qa.request_id,attempt:1,status:'saved',receipt_revision:2,draft_revision:0});
assert.equal(queue.next().raw.patient_name,'A continued');
console.log('Ledger component queue: 7 additional assertions passed');
const { EditorRegistry } = require('../assets/ledger_editor/state.js');
const registry = new EditorRegistry(() => `registry-${++sequence}`);
const dayA=registry.select('day-a');dayA.sync([base]);dayA.edit('a','patient_name','400ms 이전 미전송');
registry.select('day-b').sync([{...base,raw:{...base.raw,patient_name:'다른 날짜'}}]);
registry.select('day-b').edit('a','patient_name','다른 날짜 미저장');
assert.equal(registry.select('day-a').rows.get('a').raw.patient_name,'400ms 이전 미전송');
const beforeLeave=dayA.next();dayA.ack({id:'a',request_id:beforeLeave.request_id,status:'error',message:'서버 연결 실패'});
registry.select('day-b');assert.equal(registry.select('day-a').rows.get('a').failed.request_id,beforeLeave.request_id);
const checkpoint=JSON.parse(JSON.stringify(registry.snapshot()));
const recovered = new EditorRegistry(() => `recover-${++sequence}`, checkpoint);
const resumed=recovered.select('day-a');assert.equal(resumed.rows.get('a').raw.patient_name,'400ms 이전 미전송');
resumed.retry('a');assert.equal(resumed.next().request_id,beforeLeave.request_id,'workspace remount retains immutable retry ID');
assert.equal(recovered.select('day-b').rows.get('a').raw.patient_name,'다른 날짜 미저장');
const queued=recovered.select('new-day');queued.add({patient_name:'초안',payments:{}},'new');queued.edit('new','patient_name','한글 조합중');queued.composing.add('new');
const remounted=new EditorRegistry(undefined,recovered.snapshot()).select('new-day');
assert.equal(remounted.next().raw.patient_name,'한글 조합중','remount preserves text and releases obsolete IME lock');
console.log('Ledger scope transitions and session checkpoint recovery: 6 assertions passed');
const imeNavigation=new EditorRegistry(()=>`ime-${++sequence}`);
const imeDay=imeNavigation.select('ime-a');imeDay.sync([base]);imeDay.edit('a','patient_name','입력 조합');imeDay.composing.add('a');
imeNavigation.select('ime-b');
assert.equal(imeNavigation.select('ime-a').next()?.raw.patient_name,'입력 조합','leaving a scope must release the removed input IME lock');
console.log('Ledger IME navigation lock release passed');
const cancellation=new EditorState('cancel',()=>`cancel-${++sequence}`);cancellation.sync([base]);
cancellation.edit('a','note','cancel');cancellation.rows.get('a').action='void';const vc=cancellation.next();
cancellation.edit('a','patient_name','취소 응답 전 입력');
cancellation.ack({id:'a',request_id:vc.request_id,status:'saved',receipt_revision:2,draft_revision:0,voided:true});
assert.equal(cancellation.next(),null,'void ACK cannot trigger a new save on the voided receipt');
console.log('Ledger void ACK supersedes queued edits passed');
await import('./smoke_ledger_transport.mjs');
